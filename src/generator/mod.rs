//! IR → source, one file per thing.
//!
//! ```text
//! Message  →  Field  →  statement
//! ```
//!
//! Rust, Go, C#, GDScript, C++ and C are generated today - each its own
//! module plus its own runtime constant ([`rust`]/[`rust_runtime`],
//! [`go`]/[`go_runtime`], [`csharp`]/[`csharp_runtime`],
//! [`gdscript`]/[`gdscript_runtime`], [`cpp`]/[`cpp_runtime`],
//! [`c`]/[`c_runtime`]) - and nothing above [`crate::ir`] moves for a
//! seventh.
//!
//! # What a run writes
//!
//! ```text
//! generated/
//!     mod.rs             the module root: declares and re-exports the rest
//!     runtime.rs         the RFC-0002 runtime, verbatim
//!     handshake.rs       fingerprints and message ids
//!     player_edge.rs     one codec
//!     player_unity.rs    another
//! ```
//!
//! One file per model per codec, never one file for the whole project: a codec
//! is the unit that changes, and a diff should show which one did.
//!
//! # It is a module tree, not something to `include!`
//!
//! `cyclonec_old` wrote one file and had the user paste it into their own
//! module, which is why nothing in it needed an import - the models were
//! already in scope at the paste site. A *tree* cannot work that way. Each file
//! here is an ordinary Rust module: it is named like one (`player_edge.rs`, not
//! `player.edge.rs` - a dot is not part of an identifier, so `mod` could never
//! reach it), it `use`s every type it names, including the model it encodes,
//! and the whole tree is mounted the ordinary way:
//!
//! ```ignore
//! mod generated;
//! use generated::{PlayerEdgeCodec, Reader, Writer};
//! ```
//!
//! Which leaves one thing the generator has to be told rather than assume:
//! *where the models live*. It reads that off the source layout by default -
//! `src/models/player.rs` is `crate::models::player` - and `model_path` in
//! `cyclone.toml` overrides it. See [`crate::generate::model_paths`].
//!
//! The tree is flat. Model names are unique within a schema, so
//! `<model>_<codec>` is unique too, and a flat tree is one every file reaches
//! with a single `super::`.

pub mod c;
